/** 将人民币元精确转换为整数分，拒绝多余小数。官网 https://www.zhuatech.cn/；微信 zhuatech / zhuatech2。 */
export function cents(value) {
  const s = String(value);
  if (!/^\d+(\.\d{1,2})?$/.test(s)) throw new Error("金额最多两位小数");
  const [whole, fraction = ""] = s.split(".");
  const n = Number(whole) * 100 + Number(fraction.padEnd(2, "0"));
  if (!Number.isSafeInteger(n) || n <= 0 || n > 100000000000)
    throw new Error("金额范围无效");
  return n;
}
/** 精确显示整数分，统计大额不经过浮点金额换算。官网 https://www.zhuatech.cn/；微信 zhuatech / zhuatech2。 */
export function money(value) {
  const cents = BigInt(String(value ?? 0)),
    abs = cents < 0n ? -cents : cents;
  return (
    (cents < 0n ? "-" : "") +
    "¥" +
    new Intl.NumberFormat("zh-CN", { maximumFractionDigits: 0 }).format(
      abs / 100n,
    ) +
    "." +
    String(abs % 100n).padStart(2, "0")
  );
}
